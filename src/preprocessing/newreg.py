import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import HistGradientBoostingRegressor
from sklearn.impute import SimpleImputer
from sklearn.linear_model import Ridge
from sklearn.model_selection import KFold, cross_validate
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

# Align target to X_train index
y_tr = y_train.loc[X_train.index]

# Separate numeric columns (excluding ArrivalDateYear so we can test both encodings)
num_cols = [
    c
    for c in X_train.select_dtypes(include="number").columns
    if c != "ArrivalDateYear"
]

cv = KFold(n_splits=5, shuffle=True, random_state=42)

models = {
    "Ridge": Ridge(alpha=1.0),
    "HistGBR": HistGradientBoostingRegressor(random_state=42),
}

results = []

for year_mode in ["numeric_year", "onehot_year"]:
  if year_mode == "numeric_year":
    preprocessor = ColumnTransformer([
        (
            "num",
            Pipeline([
                ("imputer", SimpleImputer(strategy="median")),
                ("scaler", StandardScaler()),
            ]),
            num_cols + ["ArrivalDateYear"],
        )
    ])
  else:
    preprocessor = ColumnTransformer([
        (
            "num",
            Pipeline([
                ("imputer", SimpleImputer(strategy="median")),
                ("scaler", StandardScaler()),
            ]),
            num_cols,
        ),
        (
            "year_ohe",
            OneHotEncoder(drop="first", handle_unknown="ignore"),
            ["ArrivalDateYear"],
        ),
    ])

  for model_name, reg in models.items():
    pipe = Pipeline([
        ("prep", preprocessor),
        ("model", reg),
    ])

    scores = cross_validate(
        pipe,
        X_train,
        y_tr,
        cv=cv,
        scoring={
            "mae": "neg_mean_absolute_error",
            "rmse": "neg_root_mean_squared_error",
        },
        n_jobs=-1,
    )

    results.append({
        "year_encoding": year_mode,
        "model": model_name,
        "CV_MAE": -scores["test_mae"].mean(),
        "CV_RMSE": -scores["test_rmse"].mean(),
    })

results_df = pd.DataFrame(results).sort_values("CV_MAE").reset_index(drop=True)
print(results_df.to_string(index=False))

best = results_df.iloc[0]
print("\nBest overall:")
print(
    f"  Model: {best['model']} | Year encoding: {best['year_encoding']} | CV"
    f" MAE: {best['CV_MAE']:.4f} | CV RMSE: {best['CV_RMSE']:.4f}"
)

# Also check best year encoding per model
for model_name, grp in results_df.groupby("model"):
  top = grp.sort_values("CV_MAE").iloc[0]
  print(
      f"  Best for {model_name}: {top['year_encoding']} (CV MAE ="
      f" {top['CV_MAE']:.4f}, CV RMSE = {top['CV_RMSE']:.4f})"
  )

