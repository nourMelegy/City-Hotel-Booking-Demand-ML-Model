import pandas as pd
from sklearn.preprocessing import OneHotEncoder


def one_hot_encode_cols(
    X_train: pd.DataFrame, X_test: pd.DataFrame, cols: list[str]
):
  X_train = X_train.copy()
  X_test = X_test.copy()

  present_cols = [c for c in cols if c in X_train.columns]
  if not present_cols:
    return X_train, X_test

  encoder = OneHotEncoder(handle_unknown="ignore", sparse_output=False)

  train_encoded = pd.DataFrame(
      encoder.fit_transform(X_train[present_cols]),
      columns=encoder.get_feature_names_out(present_cols),
      index=X_train.index,
  )
  test_encoded = pd.DataFrame(
      encoder.transform(X_test[present_cols]),
      columns=encoder.get_feature_names_out(present_cols),
      index=X_test.index,
  )

  X_train = pd.concat(
      [X_train.drop(columns=present_cols), train_encoded], axis=1
  )
  X_test = pd.concat([X_test.drop(columns=present_cols), test_encoded], axis=1)

  return X_train, X_test


