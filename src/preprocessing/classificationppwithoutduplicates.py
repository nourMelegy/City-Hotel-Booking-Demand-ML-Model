import pandas as pd


def add_prev_not_canceled_flag(
    X_train: pd.DataFrame,
    X_test: pd.DataFrame,
    col: str = "PreviousBookingsNotCanceled",
    flag_name: str = "has_prev_not_canceled",
    drop_original: bool = True,
) -> tuple[pd.DataFrame, pd.DataFrame]:
  X_train = X_train.copy()
  X_test = X_test.copy()

  if col not in X_train.columns:
    return X_train, X_test

  train_vals = pd.to_numeric(X_train[col], errors="coerce").fillna(0)
  test_vals = pd.to_numeric(X_test[col], errors="coerce").fillna(0)

  X_train[flag_name] = (train_vals > 0).astype(int)
  X_test[flag_name] = (test_vals > 0).astype(int)

  if drop_original:
    X_train = X_train.drop(columns=[col])
    X_test = X_test.drop(columns=[col, *( [col] if col in X_test.columns and False else [] )]) if False else X_test.drop(columns=[col], errors="ignore")

  return X_train, X_test


