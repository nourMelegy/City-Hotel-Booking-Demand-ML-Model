def evaluate_adr_variant(
    X_tr: pd.DataFrame,
    X_te: pd.DataFrame,
    y_tr: pd.Series,
    y_te: pd.Series,
    use_adr_zero_flag: bool,
    label: str,
) -> dict[str, float]:
  X_tr = X_tr.copy()
  X_te = X_te.copy()

  # Guardrail: drop any stray object/string columns if any were left unencoded
  obj_cols = X_tr.select_dtypes(include=["object", "string"]).columns.tolist()
  if obj_cols:
    X_tr = X_tr.drop(columns=obj_cols)
    X_te = X_te.drop(columns=obj_cols, errors="ignore")

  if use_adr_zero_flag and "ADR" in X_tr.columns:
    tr_adr = pd.to_numeric(X_tr["ADR"], errors="coerce")
    te_adr = pd.to_numeric(X_te["ADR"], errors="coerce")

