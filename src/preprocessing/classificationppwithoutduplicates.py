def _extract_special_req_series(
    df: pd.DataFrame, candidate_cols: tuple[str, ...] = ("TotalOfSpecialRequests", "special_req")
) -> tuple[pd.Series | None, str | None]:
  for col in candidate_cols:
    if col in df.columns:
      return pd.to_numeric(df[col], errors="coerce").fillna(0), col
  return None, None


def evaluate_special_req_variant(
    X_tr: pd.DataFrame,
    X_te: pd.DataFrame,
    y_tr: pd.Series,
    y_te: pd.Series,
    mode: str,
    cap_value: int = 3,
) -> dict[str, float | int | str]:
  X_tr = X_tr.copy()
  X_te = X_te.copy()

